"""Generate one thin Kaggle notebook (+ kernel-metadata.json) per training job.

    python -m training.make_notebook --config training/configs/m2_clip_probe.yaml --owner <kaggle-user> \
        [--repo-url https://github.com/<you>/codmav.git] [--ref main]
    kaggle kernels push -p kaggle/build/m2_clip_probe_ffpp_c23

The notebook:
  1. gets the code: git clone (internet on) or unzip the attached codmav-src dataset (internet off);
  2. installs extras from the attached codmav-wheels dataset when offline, else from PyPI;
  3. links attached weight datasets into the cache dirs the libraries expect;
  4. runs `python -m training.run --mode full --resume auto`, which writes checkpoints,
     metrics and artifacts under /kaggle/working/runs/<run_name>/ and resumes from the
     newest checkpoint found in /kaggle/working or in an attached previous version's output.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

from training.config import load_job_config
from training.paths import REPO_ROOT

DATASETS_YAML = REPO_ROOT / "training" / "datasets.yaml"


def _md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}


def _code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip("\n").splitlines(keepends=True)}


def resolve_sources(cfg: dict, owner: str, registry: dict,
                    repo_url: str | None = None) -> tuple[list[str], list[str], list[str], list[str]]:
    """Return (dataset_sources, competition_sources, kernel_sources, warnings)."""
    ds, comp, kern, warn = [], [], [], []
    for name in (cfg.get("data") or {}).get("datasets", []):
        entry = registry["datasets"].get(name)
        if entry is None:
            raise ValueError(f"unknown dataset {name!r}; add it to training/datasets.yaml")
        if not entry.get("kaggle_ref"):
            warn.append(f"dataset {name!r} has no verified kaggle_ref; add it in the Kaggle UI "
                        f"(Add Input) or fill training/datasets.yaml")
            continue
        {"competition": comp, "kernel_output": kern}.get(entry["kind"], ds).append(entry["kaggle_ref"])
    kg = cfg.get("kaggle") or {}
    for w in kg.get("weights_datasets", []):
        ds.append(f"{owner}/{w}")
    if not kg.get("internet", True):
        ds += [f"{owner}/codmav-src", f"{owner}/codmav-wheels"]
    elif not repo_url:
        ds.append(f"{owner}/codmav-src")     # no git repo to clone -> code comes from the source dataset
    return sorted(set(ds)), sorted(set(comp)), sorted(set(kern)), warn


def build_notebook(cfg: dict, config_rel: str, repo_url: str | None, ref: str) -> dict:
    kg = cfg.get("kaggle") or {}
    pkgs = " ".join(kg.get("pip_packages", []))
    run_name = cfg["run_name"]
    cells = [
        _md(f"""
# codmav training job: `{cfg['job']}` ({run_name})
Generated by `training/make_notebook.py` from `{config_rel}`. Do not edit by hand; regenerate instead.

* Mode: **full**. Checkpoints every {cfg['checkpoint'].get('every_steps', '?')} steps / {cfg['checkpoint'].get('every_minutes', '?')} min
  to `/kaggle/working/runs/{run_name}/checkpoints`.
* **Resume after a dead session:** open the notebook, *Add Input -> Your Work -> this notebook's previous version output*,
  then Run All. The runner picks the newest checkpoint automatically.
* Outputs to download: `/kaggle/working/runs/{run_name}/` (artifacts/, run_manifest.json, metrics.json).
"""),
        _code(f"""
import os, sys, subprocess, glob, zipfile, shutil, pathlib
REPO_URL = {repo_url!r}
REF = {ref!r}
WORK = pathlib.Path('/kaggle/working')
CODE = WORK / 'codmav'
def sh(cmd):
    print('$', cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True)

def internet_ok():
    import socket
    try:
        socket.create_connection(('pypi.org', 443), timeout=3).close(); return True
    except OSError:
        return False
ONLINE = internet_ok()
print('internet:', ONLINE)
"""),
        _code("""
# 1) Code: zip or auto-extracted folder from the codmav-src dataset (any mount layout), else git clone
if CODE.exists():
    shutil.rmtree(CODE)
def find_src():
    # Bounded depth only: a recursive glob over /kaggle/input walks every attached dataset (100k+ files).
    # Mount layouts: /kaggle/input/<slug>/ and /kaggle/input/datasets/<owner>/<slug>/ (+ auto-extracted zip dir)
    pats = [f'/kaggle/input/{"*/" * d}codmav_src.zip' for d in range(1, 5)]
    for pat in pats:
        hits = glob.glob(pat)
        if hits:
            return 'zip', hits[0]
    for d in range(1, 5):
        for marker in glob.glob(f'/kaggle/input/{"*/" * d}training/run.py'):
            root = pathlib.Path(marker).parents[1]
            if (root / 'ml').is_dir() and (root / 'backend').is_dir():
                return 'dir', str(root)
    return None, None
kind, src = find_src()
if kind == 'zip':
    zipfile.ZipFile(src).extractall(CODE)
elif kind == 'dir':
    shutil.copytree(src, CODE)
elif ONLINE and REPO_URL:
    sh(f'git clone --depth 1 --branch {REF} {REPO_URL} {CODE}')
    os.environ['CODMAV_GIT_SHA'] = subprocess.check_output(['git', '-C', str(CODE), 'rev-parse', 'HEAD'], text=True).strip()
else:
    raise SystemExit('No code source: attach the codmav-src dataset or enable internet and set REPO_URL')
print('code from', kind or 'git', src or REPO_URL)
sys.path.insert(0, str(CODE))
os.chdir(CODE)
"""),
        _code(f"""
# 2) Dependencies (torch / torchvision / numpy are preinstalled on Kaggle images)
PKGS = {pkgs!r}
base = 'pydantic pydantic-settings PyYAML structlog av'
wheels = [p for d in range(1, 4) for p in glob.glob(f'/kaggle/input/{{"*/" * d}}wheels')]
if ONLINE:
    sh(f'pip install -q {{base}} {{PKGS}}'.strip())
elif wheels:
    sh(f'pip install -q --no-index --find-links {{wheels[0]}} {{base}} {{PKGS}}'.strip())
else:
    print('WARNING: offline and no wheel dataset attached; relying on preinstalled packages')
"""),
        _code("""
# 3) Pretrained weights from attached datasets -> expected cache locations
os.environ['CODMAV_WEIGHTS_DIRS'] = os.pathsep.join(p for d in range(0, 3) for p in glob.glob(f'/kaggle/input/{"*/" * d}codmav-weights-*'))
print('weights dirs:', os.environ['CODMAV_WEIGHTS_DIRS'] or '(none attached)')
os.environ['CODMAV_INPUT_ROOTS'] = '/kaggle/input'
os.environ['CODMAV_OUTPUT_ROOT'] = '/kaggle/working/runs'
"""),
        _code(f"""
# 4) Train (resumes automatically from the newest checkpoint it can find)
sh('python -m training.run --config {config_rel} --mode full --resume auto')
"""),
        _code(f"""
# 5) Summary + keep /kaggle/working small (Kaggle output limit): drop old checkpoints, keep artifacts
import json
run_dir = WORK / 'runs' / {run_name!r}
print(json.dumps(json.load(open(run_dir / 'run_manifest.json'))['metrics'], indent=2))
shutil.rmtree(CODE, ignore_errors=True)   # code is reproducible from git sha in run_manifest.json
"""),
    ]
    return {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                                        "name": "python3"},
                                         "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 5}


def generate(config_path: Path, owner: str, out_root: Path, repo_url: str | None = None, ref: str = "main") -> Path:
    cfg = load_job_config(config_path, "full")
    registry = yaml.safe_load(DATASETS_YAML.read_text(encoding="utf-8"))
    ds, comp, kern, warnings = resolve_sources(cfg, owner, registry, repo_url)
    kg = cfg.get("kaggle") or {}
    try:
        config_rel = config_path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        config_rel = config_path.as_posix()
    out = out_root / cfg["run_name"]
    out.mkdir(parents=True, exist_ok=True)
    nb_name = f"{cfg['run_name']}.ipynb"
    (out / nb_name).write_text(json.dumps(build_notebook(cfg, config_rel, repo_url, ref), indent=1),
                               encoding="utf-8")
    slug = cfg["run_name"].replace("_", "-").lower()
    meta = {
        "id": f"{owner}/codmav-{slug}",
        "title": f"codmav {slug}",
        "code_file": nb_name,
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": kg.get("accelerator") == "gpu",
        "enable_internet": bool(kg.get("internet", True)),
        "dataset_sources": ds,
        "competition_sources": comp,
        "kernel_sources": kern,
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    for w in warnings:
        print("WARNING:", w)
    if not cfg.get("implemented", True):
        print(f"NOTE: job {cfg['job']} is not implemented yet; the notebook will exit with a clear message.")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True, type=Path, nargs="+")
    ap.add_argument("--owner", required=True, help="your Kaggle username")
    ap.add_argument("--repo-url", default=None)
    ap.add_argument("--ref", default="main")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "kaggle" / "build")
    a = ap.parse_args()
    for c in a.config:
        print("wrote", generate(c, a.owner, a.out, a.repo_url, a.ref))


if __name__ == "__main__":
    main()
